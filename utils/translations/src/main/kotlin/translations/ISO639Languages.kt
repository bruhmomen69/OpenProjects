    /**
     * Gets the base language code from a locale (e.g., "en" from "en_US").
     */
    fun getBaseLanguage(locale: String): String {
        return locale.substringBefore('_').lowercase()
    }

    /**
     * Validates if a locale string is valid (either ISO 639-1 or ISO 639-1_ISO 3166-1).
     */
    fun isValidLocale(locale: String): Boolean {
        val parts = locale.split('_')
        if (parts.isEmpty() || parts.size > 2) return false
        
        val language = parts[0].lowercase()
        if (!ALL_LANGUAGES.containsKey(language)) return false
        
        if (parts.size == 2) {
            val region = parts[1].uppercase()
            // Basic validation: region should be 2 uppercase letters
            if (region.length != 2 || !region.all { it.isLetter() }) return false
        }
        
        return true
    }
